// Package exporter renders Policy IR into runtime and SDK artifacts.
package exporter

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/caplock/caplock/internal/policy"
)

// Document is the normalized SDK configuration derived from Policy IR.
type Document struct {
	Version  int              `json:"version" yaml:"version"`
	Policy   string           `json:"policy" yaml:"policy"`
	Defaults policy.Defaults  `json:"defaults" yaml:"defaults"`
	Subjects []policy.Subject `json:"subjects" yaml:"subjects"`
	Rules    []policy.Rule    `json:"rules" yaml:"rules"`
}

// Render exports a policy in json, yaml, or rego form.
func Render(ir *policy.IR, format string) ([]byte, error) {
	if ir == nil {
		return nil, errors.New("policy is nil")
	}
	document := Document{
		Version:  ir.IRVersion,
		Policy:   ir.Policy,
		Defaults: ir.Defaults,
		Subjects: nonNilSubjects(ir.Subjects),
		Rules:    nonNilRules(ir.Rules),
	}
	switch strings.ToLower(format) {
	case "json", "sdk":
		data, err := json.MarshalIndent(document, "", "  ")
		if err != nil {
			return nil, err
		}
		return append(data, '\n'), nil
	case "yaml", "yml":
		data, err := yaml.Marshal(document)
		if err != nil {
			return nil, err
		}
		return data, nil
	case "rego":
		return rego(ir)
	case "cedar":
		return cedar(ir)
	default:
		return nil, fmt.Errorf("unsupported export format %q; use json, sdk, yaml, rego, or cedar", format)
	}
}

func nonNilSubjects(values []policy.Subject) []policy.Subject {
	if values == nil {
		return []policy.Subject{}
	}
	return values
}

func nonNilRules(values []policy.Rule) []policy.Rule {
	if values == nil {
		return []policy.Rule{}
	}
	return values
}

func rego(ir *policy.IR) ([]byte, error) {
	rules, err := regoRules(ir.Rules)
	if err != nil {
		return nil, err
	}
	ruleJSON, err := json.Marshal(rules)
	if err != nil {
		return nil, err
	}
	defaultJSON, err := json.Marshal(ir.Defaults)
	if err != nil {
		return nil, err
	}
	output := fmt.Sprintf(regoModule, string(defaultJSON), string(ruleJSON))
	return []byte(output), nil
}

func regoRules(rules []policy.Rule) ([]map[string]any, error) {
	raw, err := json.Marshal(rules)
	if err != nil {
		return nil, err
	}
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.UseNumber()
	var result []map[string]any
	if err := decoder.Decode(&result); err != nil {
		return nil, err
	}
	for index := range result {
		match, ok := result[index]["match"].(map[string]any)
		if !ok {
			return nil, errors.New("policy rule has no match object")
		}
		contextValue, ok := match["context"].(map[string]any)
		if !ok {
			continue
		}
		timeValue, ok := contextValue["time"].(map[string]any)
		if !ok {
			continue
		}
		spec, ok := timeValue["outside"].(string)
		if !ok {
			return nil, errors.New("policy time window is not a string")
		}
		compiled, err := policy.CompileTimeWindow(spec)
		if err != nil {
			return nil, err
		}
		timeValue["outside"] = map[string]any{
			"days":        compiled.Days,
			"startMinute": compiled.StartMinute,
			"endMinute":   compiled.EndMinute,
			"timezone":    compiled.Timezone,
		}
	}
	return result, nil
}

const regoModule = `# Generated by Caplock. Do not edit by hand.
#
# Input contract:
#   input.subject, input.tool, input.capabilities, input.dataClass, input.sink
#   input.args, input.provenance
#   input.context.environment, input.context.attributes
#   input.context.weekday (0=Sunday), input.context.minute (local wall clock)
package caplock

defaults := %s
rules := %s

decision := {"effect": defaults.effect, "ruleId": "", "default": true, "obligations": []} if {
  not any_match
}

any_match if {
  req := input
  some i
  rule_matches(rules[i], req)
}

decision := d if {
  req := input
  matches := [i | some i; rule_matches(rules[i], req)]
  count(matches) > 0
  best_rank := min([effect_rank(rules[i].effect) | i := matches[_]])
  best_priority := max([priority(rules[i]) | i := matches[_]; effect_rank(rules[i].effect) == best_rank])
  candidates := [i | i := matches[_]; effect_rank(rules[i].effect) == best_rank; priority(rules[i]) == best_priority]
  best_index := min(candidates)
  best := rules[best_index]
  d := {"effect": best.effect, "ruleId": best.id, "default": false, "obligations": object.get(best, "obligations", [])}
}

effect_rank(effect) := 0 if { effect == "deny" }
effect_rank(effect) := 1 if { effect == "require_approval" }
effect_rank(effect) := 2 if { effect == "allow" }
priority(rule) := p if { p := object.get(rule, "priority", 0) }

rule_matches(rule, req) if {
  match := rule.match
  subject_ok(match, req)
  tool_ok(match, req)
  capability_ok(match, req)
  data_class_ok(match, req)
  sink_ok(match, req)
  time_ok(match, req)
  environment_ok(match, req)
  attributes_ok(match, req)
  provenance_ok(match, req)
  args_ok(match, req)
}

subject_ok(match, req) if { not match.subject }
subject_ok(match, req) if { match.subject == "*" }
subject_ok(match, req) if { match.subject == req.subject }

tool_ok(match, req) if { not match.tool }
tool_ok(match, req) if { some value in match.tool; value == "*" }
tool_ok(match, req) if { some value in match.tool; value == req.tool }

capability_ok(match, req) if { not match.capability }
capability_ok(match, req) if { some value in match.capability; value == "*" }
capability_ok(match, req) if { some value in match.capability; some actual in req.capabilities; value == actual }

data_class_ok(match, req) if { not match.dataClass }
data_class_ok(match, req) if { some value in match.dataClass; value == "*" }
data_class_ok(match, req) if { some value in match.dataClass; some actual in req.dataClass; value == actual }

sink_ok(match, req) if { not match.sink }
sink_ok(match, req) if { match.sink == "*" }
sink_ok(match, req) if { match.sink == req.sink }

environment_ok(match, req) if { not match.context.environment }
environment_ok(match, req) if { match.context.environment == "*" }
environment_ok(match, req) if { match.context.environment == req.context.environment }

attributes_ok(match, req) if { not match.context.attributes }
attributes_ok(match, req) if {
  every key, value in match.context.attributes { attribute_ok(key, value, req.context.attributes) }
}
attribute_ok(key, value, attributes) if { value == "*"; _ = attributes[key] }
attribute_ok(key, value, attributes) if { attributes[key] == value }

provenance_ok(match, req) if { not match.provenance }
provenance_ok(match, req) if { some value in match.provenance.contains; value == "*" }
provenance_ok(match, req) if { some value in match.provenance.contains; some actual in req.provenance; value == actual }

time_ok(match, req) if { not match.context.time }
time_ok(match, req) if { window := match.context.time.outside; outside(window, req) }
outside(window, req) if { not inside(window, req) }
inside(window, req) if {
  window.startMinute < window.endMinute
  some day in window.days
  day == req.context.weekday
  req.context.minute >= window.startMinute
  req.context.minute < window.endMinute
}
inside(window, req) if {
  window.startMinute > window.endMinute
  some day in window.days
  day == req.context.weekday
  req.context.minute >= window.startMinute
}
inside(window, req) if {
  window.startMinute > window.endMinute
  previous := (req.context.weekday + 6) %% 7
  some day in window.days
  day == previous
  req.context.minute < window.endMinute
}
inside(window, req) if {
  window.startMinute == window.endMinute
  some day in window.days
  day == req.context.weekday
}

args_ok(match, req) if { not match.args }
args_ok(match, req) if {
  every key, selector in match.args { arg_selector_ok(req.args, key, selector) }
}

arg_selector_ok(args, key, selector) if {
  not is_object(selector)
  value := arg_value(args, key)
  value == selector
}
arg_selector_ok(args, key, selector) if {
  is_object(selector)
  not has_operator(selector)
  value := arg_value(args, key)
  value == selector
}
arg_selector_ok(args, key, selector) if { selector["$exists"] == true; arg_exists(args, key) }
arg_selector_ok(args, key, selector) if { selector["$exists"] == false; not arg_exists(args, key) }
arg_selector_ok(args, key, selector) if { value := arg_value(args, key); value != selector["$ne"] }
arg_selector_ok(args, key, selector) if { not arg_exists(args, key); _ = selector["$ne"] }
arg_selector_ok(args, key, selector) if { value := arg_value(args, key); expected := selector["$in"]; some candidate in expected; candidate == value }
arg_selector_ok(args, key, selector) if {
  value := arg_value(args, key)
  expected := selector["$contains"]
  is_string(value)
  is_string(expected)
  contains(value, expected)
}
arg_selector_ok(args, key, selector) if {
  value := arg_value(args, key)
  expected := selector["$contains"]
  is_array(value)
  some item in value
  some candidate in expected
  item == candidate
}
arg_selector_ok(args, key, selector) if { value := arg_value(args, key); regex.match(selector["$regex"], value) }
arg_selector_ok(args, key, selector) if { value := arg_value(args, key); startswith(value, selector["$prefix"]) }
arg_selector_ok(args, key, selector) if { value := arg_value(args, key); endswith(value, selector["$suffix"]) }

has_operator(selector) if { some key in object.keys(selector); startswith(key, "$") }
arg_exists(args, key) if { _ = arg_value(args, key) }
arg_value(args, path) := value if {
  is_object(args)
  parts := split(path, ".")
  walk(args, [walkPath, value])
  walkPath == parts
}
`
