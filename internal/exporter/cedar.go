package exporter

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/caplock/caplock/internal/policy"
)

// cedar renders the representable Policy IR subset as Cedar. Caplock deny and
// require_approval rules both become Cedar forbid: Cedar has no approval
// primitive, so converting approval to a block preserves fail-closed behavior.
// Time windows and non-equality argument operators are rejected rather than
// approximated silently.
func cedar(ir *policy.IR) ([]byte, error) {
	var builder strings.Builder
	builder.WriteString("// Generated by Caplock. Do not edit by hand.\n")
	builder.WriteString("// Context contract: subject, tool, capabilities, dataClass, provenance, sink, args, environment, attributes.\n")
	builder.WriteString("// require_approval is exported as forbid because Cedar has no approval primitive.\n\n")
	if ir.Defaults.Effect == policy.EffectAllow {
		builder.WriteString("// defaults.effect=allow\npermit (principal, action, resource);\n\n")
	} else {
		builder.WriteString("// defaults.effect=deny: unmatched requests are not permitted.\n\n")
	}
	for _, rule := range ir.Rules {
		effect := "permit"
		if rule.Effect == policy.EffectDeny || rule.Effect == policy.EffectRequireApproval {
			effect = "forbid"
		}
		conditions, err := cedarConditions(rule.Match)
		if err != nil {
			return nil, fmt.Errorf("cedar export rule %q: %w", rule.ID, err)
		}
		fmt.Fprintf(&builder, "// rule: %s effect=%s\n", safeComment(rule.ID), rule.Effect)
		builder.WriteString(effect)
		builder.WriteString(" (principal, action, resource)")
		if len(conditions) > 0 {
			builder.WriteString(" when {\n  ")
			builder.WriteString(strings.Join(conditions, " &&\n  "))
			builder.WriteString("\n}")
		}
		builder.WriteString(";\n\n")
	}
	return []byte(builder.String()), nil
}

func cedarConditions(match *policy.Match) ([]string, error) {
	if match == nil {
		return nil, nil
	}
	conditions := make([]string, 0)
	if match.Subject != "" && match.Subject != "*" {
		conditions = append(conditions, "context.subject == "+quoted(match.Subject))
	}
	if condition := cedarStringEquals("context.tool", match.Tool); condition != "" {
		conditions = append(conditions, condition)
	}
	if condition := cedarStringSet("context.capabilities", match.Capability); condition != "" {
		conditions = append(conditions, condition)
	}
	if condition := cedarStringSet("context.dataClass", match.DataClass); condition != "" {
		conditions = append(conditions, condition)
	}
	if match.Sink != "" && match.Sink != "*" {
		conditions = append(conditions, "context.sink == "+quoted(match.Sink))
	}
	if match.Context != nil {
		if match.Context.Time != nil {
			return nil, fmt.Errorf("time windows cannot be represented in Cedar export")
		}
		if match.Context.Environment != "" && match.Context.Environment != "*" {
			conditions = append(conditions, "context.environment == "+quoted(match.Context.Environment))
		}
		keys := make([]string, 0, len(match.Context.Attributes))
		for key := range match.Context.Attributes {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			value := match.Context.Attributes[key]
			if value == "*" {
				continue
			}
			conditions = append(conditions, fmt.Sprintf("context.attributes has %s && context.attributes[%s] == %s", quoted(key), quoted(key), quoted(value)))
		}
	}
	if match.Provenance != nil {
		if condition := cedarStringSet("context.provenance", []string(match.Provenance.Contains)); condition != "" {
			conditions = append(conditions, condition)
		}
	}
	if len(match.Args) > 0 {
		keys := make([]string, 0, len(match.Args))
		for key := range match.Args {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			literal, err := cedarLiteral(match.Args[key])
			if err != nil {
				return nil, fmt.Errorf("argument %q: %w", key, err)
			}
			conditions = append(conditions, fmt.Sprintf("context.args has %s && context.args[%s] == %s", quoted(key), quoted(key), literal))
		}
	}
	return conditions, nil
}

func cedarStringSet(path string, selectors []string) string {
	parts := make([]string, 0, len(selectors))
	for _, selector := range selectors {
		if selector == "*" {
			return ""
		}
		parts = append(parts, fmt.Sprintf("%s.contains(%s)", path, quoted(selector)))
	}
	if len(parts) == 0 {
		return ""
	}
	if len(parts) == 1 {
		return parts[0]
	}
	return "(" + strings.Join(parts, " || ") + ")"
}

func cedarStringEquals(path string, selectors []string) string {
	parts := make([]string, 0, len(selectors))
	for _, selector := range selectors {
		if selector == "*" {
			return ""
		}
		parts = append(parts, fmt.Sprintf("%s == %s", path, quoted(selector)))
	}
	if len(parts) == 0 {
		return ""
	}
	if len(parts) == 1 {
		return parts[0]
	}
	return "(" + strings.Join(parts, " || ") + ")"
}

func cedarLiteral(value any) (string, error) {
	switch typed := value.(type) {
	case string:
		return quoted(typed), nil
	case bool:
		if typed {
			return "true", nil
		}
		return "false", nil
	case int, int8, int16, int32, int64, uint, uint8, uint16, uint32, uint64, float32, float64, json.Number:
		encoded, err := json.Marshal(typed)
		if err != nil {
			return "", err
		}
		return string(encoded), nil
	default:
		return "", fmt.Errorf("only scalar equality is supported, got %T (operators and composite values are rejected)", value)
	}
}

func quoted(value string) string {
	encoded, _ := json.Marshal(value)
	return string(encoded)
}

func safeComment(value string) string {
	return strings.Map(func(character rune) rune {
		if character == '\n' || character == '\r' || character == '\x00' {
			return ' '
		}
		return character
	}, value)
}
